export function launchPackageScriptCommandIssues(scripts) {
  const source = scripts && typeof scripts === "object" && !Array.isArray(scripts) ? scripts : {};
  const issues = [];
  for (const [name, expected] of Object.entries(EXACT_LAUNCH_PACKAGE_SCRIPTS)) {
    const actual = source[name];
    if (typeof actual !== "string") {
      issues.push({ name, reason: "missing" });
    } else if (actual !== expected) {
      issues.push({ name, reason: "mismatch" });
    }
  }
  return issues;
}
